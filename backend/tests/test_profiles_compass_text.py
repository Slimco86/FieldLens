def test_extensionless_upload_is_accepted_and_yields_stations(
    migrated_url: URL, tmp_path: Path
) -> None:
    api = make_api(migrated_url, tmp_path)
    data = report().replace("\n", "\r\n").encode("cp1252")
    pid, docs = _ingest(api, [("Volve F_F-99_F-99_F-99_ACTUAL", data)])
    doc = docs[0]
    assert doc["format_family"] == "text"
    assert doc["origin_metadata"]["text_encoding"] == "cp1252"
    assert doc["extraction_state"] == "pending_extraction"
    did = str(doc["document_id"])
    _drain(api)
    rep = _report(api, pid, did)
    assert rep["profile_name"] == "text_compass_survey_report"
    assert rep["status"] == "succeeded"
    recs = api.client.get(
        f"/api/v1/projects/{pid}/documents/{did}/extraction/records?kind=trajectory_station"
    ).json()
    assert recs["total"] == 3
    md = next(a for a in recs["items"][1]["attributes"] if a["key"].endswith(".md"))
    assert md["evidence"]["locator"]["kind"] == "text"
    assert md["evidence"]["locator"]["column_name"] == "md"
    assert (md["original_text"], md["unit"], md["number"]) == ("100.00", "m", 100.0)
    assert md["reference"] and "54.90" in md["reference"]
    assert api.documents(pid)[0]["extraction_state"] in ("extracted", "extracted_with_issues")
