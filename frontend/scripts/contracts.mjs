// Generates src/api/generated.ts from the backend OpenAPI export.
//   write: regenerate the file.   check: regenerate in memory and fail on drift (no tree writes).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const target = resolve(here, "../src/api/generated.ts");
const mode = process.argv[2];
if (mode !== "write" && mode !== "check") {
  console.error("usage: contracts.mjs write|check");
  process.exit(2);
}

const json = execFileSync("uv", ["run", "--frozen", "python", "scripts/export_contracts.py"], {
  cwd: repo,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const ast = await openapiTS(JSON.parse(json), { alphabetize: true });
const banner = "// GENERATED by `npm run generate:contracts` from the backend OpenAPI. Do not edit.\n";
const next = banner + astToString(ast);

if (mode === "write") {
  writeFileSync(target, next);
  console.log(`wrote ${target}`);
} else {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* missing counts as drift */
  }
  if (current !== next) {
    console.error("contracts drift: run `npm run generate:contracts` and review the diff");
    process.exit(1);
  }
  console.log("contracts up to date");
}
